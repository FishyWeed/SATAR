<section>
	<h2>How it works</h2>
	<ol class="flow">
		<li><strong>Request.</strong> An employee checks the register and requests a tool that is not in it.</li>
		<li><strong>Business need.</strong> The Manager of the department approves or rejects the request.</li>
		<li><strong>Data risk.</strong> The Reviewer sets the risk level, the highest data class allowed and a review date, then approves, rejects or bans the tool.</li>
	</ol>
</section>

<section>
	<h2>What you get</h2>
	<ul class="features">
		<li>A searchable register of approved and banned AI tools</li>
		<li>A two-step approval workflow with a reason for every decision</li>
		<li>The highest data class that each tool may receive</li>
		<li>Review dates, with a list of the tools that need a new check</li>
		<li>An audit log and printable reports for compliance</li>
		<li>Invite links for your staff, with roles for Employees, Managers, Reviewers and Administrators</li>
	</ul>
	<p class="muted">Built for the accountability and transparency principles of Malaysia's AI governance guidelines (AIGE) and the Personal Data Protection (Amendment) Act 2024.</p>
